"""Run both real-data tracks and write reports/eval_real.md and reports/results_real.json."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from dealroom.models.llm import LLM
from dealroom.realdata import cuad, financebench
from dealroom.retrieval.retriever import MODES

NAMES = {"bm25": "BM25", "dense": "Dense (local LSA)", "hybrid": "Hybrid (RRF)", "hybrid_rerank": "Hybrid + rerank"}


def pct(value: float) -> str:
    return f"{value * 100:.1f}%"


def run(cache: Path, reports: Path, llm: LLM | None = None) -> dict[str, Any]:
    questions = financebench.load_questions(cache / "financebench" / "questions.jsonl")
    fb = financebench.evaluate(questions, cache / "financebench" / "index", llm)
    test = cuad.load_contracts(cache / "cuad" / "test.json")
    contracts = {
        f"v{version}_{'termination' if strict else 'provision'}": cuad.evaluate(test, strict, version)
        for version in (1, 2)
        for strict in (False, True)
    }
    results = {"llm": (llm.name if llm else "stub"), "financebench": fb, "cuad": contracts}
    reports.mkdir(parents=True, exist_ok=True)
    (reports / "results_real.json").write_text(json.dumps(results, indent=1, ensure_ascii=False) + "\n")
    (reports / "eval_real.md").write_text(render(results))
    return results


def render(results: dict[str, Any]) -> str:
    fb = results["financebench"]
    lines = [
        "# Evaluation on real data",
        "",
        "Generated by `dealroom real eval`. Sources are pinned in `data/real/manifest.json` and not committed.",
        "",
        "## FinanceBench (SEC filings, human-written questions)",
        "",
        f"{fb['questions']} questions on {fb['filings']} 10-K/10-Q/8-K filings "
        "([Patronus AI](https://github.com/patronus-ai/financebench), CC BY-NC 4.0). Each question is searched "
        "within its own filing. A hit means a retrieved chunk is on a page the annotators marked as evidence. "
        "Filings are extracted as layout-sorted text without cell-level table detection.",
        "",
        "| Method | Page hit@1 | Page hit@5 | Page hit@10 |",
        "| --- | --- | --- | --- |",
    ]
    for mode in MODES:
        m = fb["retrieval"][mode]
        lines.append(f"| {NAMES[mode]} | {pct(m['page_hit@1'])} | {pct(m['page_hit@5'])} | {pct(m['page_hit@10'])} |")
    lines += [
        "",
        "Page hit@5 (hybrid + rerank) by question type: "
        + ", ".join(f"{t} {pct(v)}" for t, v in fb["page_hit@5_by_type"].items())
        + ".",
        "",
        f"Answers with model `{results['llm']}`: abstained on {fb['abstained']} of {fb['questions']} questions. "
        "Figure accuracy (questions whose gold answer is a single figure): "
        + ", ".join(f"{t} {pct(v['accuracy'])} of {v['questions']}" for t, v in fb["figure_accuracy_by_type"].items())
        + ".",
        "",
        "The offline stub only quotes passages, so it cannot answer questions that need a calculation, and its "
        "lexical abstention rule rejects most of FinanceBench's long questions. Answer quality on real filings "
        "needs a real model and has not been measured.",
        "",
        "## CUAD (commercial contracts, lawyer labels)",
        "",
        "Does a contract contain a change-of-control provision (termination, consent or notice when a party changes "
        "control)? Scored on CUAD's test split (102 contracts, "
        "[The Atticus Project](https://github.com/TheAtticusProject/cuad), CC BY 4.0). Version 1 is the pattern set "
        "written for the synthetic contracts. Version 2 was developed on CUAD's training split (408 contracts) and "
        "scored on the test split once.",
        "",
        "| Detector | Precision | Recall | F1 |",
        "| --- | --- | --- | --- |",
    ]
    labels = {
        "v1_provision": "v1, provision present",
        "v2_provision": "v2, provision present",
        "v1_termination": "v1, termination right only",
        "v2_termination": "v2, termination right only",
    }
    for key in ("v1_provision", "v2_provision", "v1_termination", "v2_termination"):
        c = results["cuad"][key]
        lines.append(f"| {labels[key]} | {pct(c['precision'])} | {pct(c['recall'])} | {c['f1']:.3f} |")
    base = results["cuad"]["v2_provision"]
    lines += [
        "",
        f"{base['with_provision']} of {base['contracts']} test contracts carry a provision. The challenger raises an "
        "argument only for a termination right, which real contracts express in many more ways than its pattern "
        "covers: it finds few of them, but every one it flags is real.",
        "",
    ]
    return "\n".join(lines)
